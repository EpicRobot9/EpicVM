function New-EpicVMUbuntuSeedIso {
    <#
        Produces an ISO 9660 image from an already-built cidata VHDX.

        The Ubuntu installer locates a NoCloud seed by scanning optical media, so
        the seed must be handed over as an ISO on the second DVD drive. A plain
        SCSI volume labelled cidata is not picked up reliably and the install
        silently drops back to the interactive installer.

        genisoimage is used from the Ubuntu WSL distro because it is the only ISO
        writer available on this host: oscdimg and the IMAPI2FS COM interface are
        both unusable here (COM's CreateResultImage overload cannot be invoked
        from PowerShell without a by-ref wrapper).
    #>
    param(
        [Parameter(Mandatory)][string]$SeedPath,
        [Parameter(Mandatory)][string]$IsoPath
    )
    if (Test-Path -LiteralPath $IsoPath) { Remove-Item -LiteralPath $IsoPath -Force }
    $wslDrive = $null
    try {
        Mount-VHD -Path $SeedPath -ErrorAction Stop | Out-Null
        $part = $null
        for ($_i = 0; $_i -lt 20; $_i++) {
            $part = Get-VHD -Path $SeedPath | Get-Disk | Get-Partition | Where-Object { $_.DriveLetter } | Select-Object -First 1
            if ($null -ne $part) { break }
            Start-Sleep -Milliseconds 500
        }
        if ($null -eq $part) { throw 'ubuntu_seed_iso_no_volume' }
        # A freshly mounted VHD can be assigned a volatile drive letter that
        # WSL does not automount under /mnt. Stage the content on the same fixed
        # volume as the seed path instead of the mounted VHD's letter.
        $seedRoot = Split-Path -Parent $SeedPath
        $driveLetter = ([IO.Path]::GetPathRoot($seedRoot)).TrimEnd('\').TrimEnd(':')
        $wslDrive = $driveLetter.ToLowerInvariant()
        $files = @(Get-ChildItem -LiteralPath ([string]$part.DriveLetter + ':\') -File -Force -ErrorAction Stop)
        if ($files.Count -eq 0) { throw 'ubuntu_seed_iso_empty' }

        # Copy the staged files into a WSL-visible staging directory. genisoimage
        # cannot read a Windows drive letter, so the content is mirrored first.
        $stageWin = Join-Path (Split-Path -Parent $SeedPath) 'seed-iso-src'
        Remove-Item -LiteralPath $stageWin -Recurse -Force -ErrorAction SilentlyContinue
        New-Item -ItemType Directory -Path $stageWin -Force | Out-Null
        foreach ($f in $files) { Copy-Item -LiteralPath $f.FullName -Destination (Join-Path $stageWin $f.Name) -Force }

        # E:\EpicVM\... -> /mnt/e/EpicVM/... . WSL mounts drives at
        # /mnt/<lowercase-letter> with no colon.
        $wslStage = '/mnt/' + $wslDrive + '/' + $stageWin.Substring(3).Replace('\','/')
        $wslIso   = '/mnt/' + $wslDrive + '/' + $IsoPath.Substring(3).Replace('\','/')

        $cmd = "set -e; rm -f '$wslIso'; genisoimage -quiet -volid CIDATA -joliet -rock -output '$wslIso' '$wslStage'; ls -l '$wslIso'"
        $result = & wsl.exe -d Ubuntu -- bash -lc $cmd 2>&1
        $exit = $LASTEXITCODE
        if ($exit -ne 0) { throw ('ubuntu_seed_iso_write_failed: {0}' -f (($result | Out-String).Trim())) }
        Remove-Item -LiteralPath $stageWin -Recurse -Force -ErrorAction SilentlyContinue
        if (-not (Test-Path -LiteralPath $IsoPath)) { throw 'ubuntu_seed_iso_missing_after_write' }
        return [ordered]@{ iso=$IsoPath; fileCount=$files.Count; bytes=(Get-Item -LiteralPath $IsoPath).Length }
    }
    finally {
        try { Dismount-VHD -Path $SeedPath -ErrorAction SilentlyContinue | Out-Null } catch { }
        $wslDrive = $null
    }
}
$plan = Get-EpicVMUbuntuPlan
$checks = Test-EpicVMUbuntuPreconditions

Write-Stage 'preflight'
foreach ($key in @('isoPresent','switchPresent','builderVmPresent','workingRootWritable','isoHashMatches')) {
    Write-Output ("  {0,-20} {1}" -f $key, $checks[$key])
}
if ($checks.Contains('isoActualSha256')) { Write-Output ("  {0,-20} {1}" -f 'isoActualSha256', $checks['isoActualSha256']) }

$report = [ordered]@{
    ok = $false
    executed = [bool]$Execute
    plan = $plan
    checks = $checks
    templatePath = $null
    imageSha256 = $null
    manifestSha256 = $null
    error = $null
}

if (-not $Execute) {
    Write-Stage 'PLAN ONLY. Re-run with -Execute from an elevated prompt to build.'
    $report.ok = $true
    $report.error = 'plan_only'
} elseif (-not $checks.isoPresent) {
    $report.error = 'iso_missing'
    Write-Stage ("FAILED: ISO not found at {0}" -f $plan.isoPath)
} elseif (-not $checks.isoHashMatches) {
    $report.error = 'iso_hash_mismatch'
    Write-Stage 'FAILED: pinned ISO sha256 does not match. Refusing to build.'
} elseif (-not $checks.switchPresent) {
    $report.error = 'switch_missing'
    Write-Stage ("FAILED: switch {0} not found" -f $plan.switch)
} else {
    $workRoot = Join-Path $plan.workingRoot ('ubuntu-' + [guid]::NewGuid().ToString('N'))
    $seedPath = Join-Path $workRoot ($plan.builderVm + '.cidata.vhdx')
    $diskPath = Join-Path $workRoot ($plan.builderVm + '.vhdx')
    try {
        Write-Stage 'generating the per-build agent password and cloud-init seed'
        $agentPassword = [Convert]::ToBase64String([Security.Cryptography.RandomNumberGenerator]::GetBytes(24))
        $hash = Get-EpicVMUbuntuPasswordHash -Password $agentPassword
        $files = New-EpicVMUbuntuCloudInit -VmName $plan.builderVm -AgentUser $plan.agentUser `
            -PasswordHash $hash -TimeZone $TimeZone -DiskSizeBytes $plan.diskSizeBytes
        $seed = New-EpicVMUbuntuSeedDisk -Path $seedPath -Files $files
        Write-Stage ("  seed written: {0} files {1}" -f @($seed.files).Count, $seed.label)

        $install = Invoke-EpicVMUbuntuInstall -VmName $plan.builderVm -SeedPath $seedPath `
            -IsoPath $plan.isoPath -Switch $plan.switch -MemoryBytes $plan.memoryBytes `
            -CpuCount $plan.cpuCount -DiskPath $diskPath
        if (-not $install.seedArgumentApplied) {
            throw 'ubuntu_seed_argument_unsupported'
        }
        Write-Stage 'booting the builder for the unattended install (this takes a while)'
        Write-Stage 'STOP HERE: the install needs to run to completion, then be sanitized and exported.'
        $report.error = 'install_started_manual_sanitization_required'
    }
    catch {
        $report.error = $_.Exception.Message
        Write-Stage ("FAILED: {0}" -f $_.Exception.Message)
    }
    finally {
        if (Test-Path -LiteralPath $workRoot) {
            Write-Output ("  workdir retained for inspection: {0}" -f $workRoot)
        }
    }
