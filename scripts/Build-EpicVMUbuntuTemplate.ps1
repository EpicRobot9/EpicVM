$passwordHash = $null
    return [ordered]@{
        'meta-data'   = ("instance-id: $VmName`nlocal-hostname: $VmName`n")
        'user-data'   = $userData
        'network-config' = @'
version: 2
ethernets:
  primary:
    match:
      name: "e*"
    dhcp4: true
    dhcp-identifier: mac
optional: true
'@
    }
}
function New-EpicVMUbuntuSeedDisk {
    <#
        Builds a 64MB FAT32 cidata VHDX. Reuses the same shape the Omarchy
        provider already uses (New-EpicVMOmarchySeedDisk) so both Linux profiles
        share one seed mechanism.
    #>
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][System.Collections.IDictionary]$Files,
        [scriptblock]$CommandInvoker = $null
    )
    function Invoke-Cmd { param([string]$Name,[hashtable]$Parameters)
        if ($null -ne $CommandInvoker) { return & $CommandInvoker $Name $Parameters }
        $command = Get-Command -Name $Name -ErrorAction SilentlyContinue
        if ($null -eq $command) { throw ("epicvm_ubuntu_provider_unavailable: {0}" -f $Name) }
        return & $Name @Parameters
    }
    $parent = Split-Path -Parent $Path
    New-Item -ItemType Directory -Path $parent -Force -ErrorAction Stop | Out-Null
    $mounted = $false
    $drive = $null
    try {
        Invoke-Cmd -Name 'New-VHD' -Parameters @{ Path=$Path; SizeBytes=67108864; Dynamic=$true; ErrorAction='Stop' } | Out-Null
        $disk = Invoke-Cmd -Name 'Mount-VHD' -Parameters @{ Path=$Path; Passthru=$true; ErrorAction='Stop' }
        $mounted = $true
        $number = [int]$disk.DiskNumber
        Invoke-Cmd -Name 'Initialize-Disk' -Parameters @{ Number=$number; PartitionStyle='GPT'; ErrorAction='Stop' } | Out-Null
        $part = Invoke-Cmd -Name 'New-Partition' -Parameters @{ DiskNumber=$number; UseMaximumSize=$true; AssignDriveLetter=$true; ErrorAction='Stop' }
        Invoke-Cmd -Name 'Format-Volume' -Parameters @{ Partition=$part; FileSystem='FAT32'; NewFileSystemLabel='cidata'; Confirm=$false; ErrorAction='Stop' } | Out-Null
        # A freshly formatted volume can return an empty DriveLetter for a
        # moment. Poll for it rather than building a broken path.
        $letter = ''
        for ($_i = 0; $_i -lt 20; $_i++) {
            $letter = [string](Invoke-Cmd -Name 'Get-Partition' -Parameters @{ DiskNumber=$number; ErrorAction='SilentlyContinue' } | Select-Object -First 1 | ForEach-Object { $_.DriveLetter })
            if (-not [string]::IsNullOrWhiteSpace($letter)) { break }
            Start-Sleep -Milliseconds 500
        }
        if ([string]::IsNullOrWhiteSpace($letter)) { throw 'ubuntu_seed_no_drive_letter' }
        $drive = $letter + ':\'
        foreach ($entry in $Files.GetEnumerator()) {
            $target = Join-Path $drive ([string]$entry.Key)
            $dir = Split-Path -Parent $target
            if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
            [IO.File]::WriteAllText($target, [string]$entry.Value, [Text.UTF8Encoding]::new($false))
        }
        return [ordered]@{ path=$Path; label='cidata'; files=@($Files.Keys) }
    }
    finally {
        if ($mounted) {
            try { Invoke-Cmd -Name 'Dismount-VHD' -Parameters @{ Path=$Path; ErrorAction='SilentlyContinue' } | Out-Null } catch { }
        }
        $drive = $null
    }
}

function Get-EpicVMUbuntuPasswordHash {
    param([Parameter(Mandatory)][string]$Password)
    $openssl = Get-Command -Name 'openssl.exe','openssl' -ErrorAction SilentlyContinue | Select-Object -First 1
    $openssl = Get-Command -Name 'openssl.exe','openssl' -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($null -eq $openssl) {
        # openssl ships inside Git for Windows but is not on PATH. Probe the
        # well-known locations before giving up.
        foreach ($candidate in @(
            'C:\Program Files\Git\usr\bin\openssl.exe',
            'C:\Program Files\Git\mingw64\bin\openssl.exe',
            'C:\Program Files (x86)\Git\usr\bin\openssl.exe')) {
            if (Test-Path -LiteralPath $candidate -PathType Leaf) {
                $openssl = [pscustomobject]@{ Source = $candidate }
                break
            }
        }
    }
    $psi = [Diagnostics.ProcessStartInfo]::new()
    $psi.FileName = $openssl.Source
    $psi.UseShellExecute = $false
    $psi.RedirectStandardInput = $true
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true
    foreach ($a in @('passwd','-6','-stdin')) { [void]$psi.ArgumentList.Add($a) }
    $p = [Diagnostics.Process]::new()
    $p.StartInfo = $psi
    try {
        [void]$p.Start()
        $p.StandardInput.Write($Password + [Environment]::NewLine)
        $p.StandardInput.Close()
        $out = $p.StandardOutput.ReadToEnd()
        [void]$p.WaitForExit(15000)
        $hash = $out.Trim()
        if (-not $hash.StartsWith('$6$')) { throw 'epicvm_ubuntu_password_hash_failed' }
        return $hash
    }
    finally { $p.Dispose() }
}

function Invoke-EpicVMUbuntuInstall {
    <#
        Runs the unattended install in a disposable builder VM. The Ubuntu server
        ISO supports the ds=nocloud-net;s=<seed> kernel argument, so the seed
        disk is attached and referenced on the kernel command line rather than
        relying on a second CD-ROM.
    #>
    param(
        [Parameter(Mandatory)][string]$VmName,
        [Parameter(Mandatory)][string]$SeedPath,
        [Parameter(Mandatory)][string]$IsoPath,
        [Parameter(Mandatory)][string]$Switch,
        [long]$MemoryBytes,
        [int]$CpuCount,
        [string]$DiskPath
    )
    Write-Stage 'creating the disposable builder VM'
    if (Get-VM -Name $VmName -ErrorAction SilentlyContinue) {
        Stop-VM -Name $VmName -Force -ErrorAction SilentlyContinue
        Remove-VM -Name $VmName -Force -ErrorAction SilentlyContinue
    }
    if (Test-Path -LiteralPath $DiskPath) { Remove-Item -LiteralPath $DiskPath -Force }
    $parent = Split-Path -Parent $DiskPath
    New-Item -ItemType Directory -Path $parent -Force | Out-Null
    $null = New-VHD -Path $DiskPath -Dynamic -SizeBytes 34359738368 -ErrorAction Stop
    # Created with NO hard disk on purpose. A default Gen2 VM on this host puts
    # the hard disk ahead of optical media in the boot order, and
    # Set-VMFirmware -FirstBootDevice hangs indefinitely, so the installer
    # ISO is never reached. An empty VM has exactly one bootable device.
    # The target disk is attached after the install completes.
    New-VM -Name $VmName -Generation 2 -MemoryStartupBytes $MemoryBytes -Path $parent -SwitchName $Switch -ErrorAction Stop | Out-Null
    # The virtual processor is not configurable in the instant after New-VM;
    # Set-VMProcessor fails with 'Modifying the properties of the device
    # Processor failed'. A short bounded settle, with a retry, is the fix.
    $cpuSet = $false
    for ($_i = 0; $_i -lt 20 -and -not $cpuSet; $_i++) {
        try {
            Set-VMProcessor -VMName $VmName -Count $CpuCount -ErrorAction Stop | Out-Null
            $cpuSet = $true
        } catch { Start-Sleep -Milliseconds 750 }
    }
    if (-not $cpuSet) { throw 'ubuntu_processor_not_configurable' }
    Set-VM -Name $VmName -AutomaticCheckpointsEnabled $false -CheckpointType Disabled -AutomaticStopAction ShutDown | Out-Null
    # Secure Boot is deliberately left at the platform default. Setting it
    # explicitly on a diskless VM fails with 'Cannot modify the secure boot
    # property', and the Ubuntu Server ISO boots correctly with Secure Boot
    # off. The published manifest records secureBoot=false accordingly.
    Set-VMKeyProtector -VMName $VmName -NewLocalKeyProtector | Out-Null
    # The installer ISO is the only bootable device on this VM.
    Add-VMDvdDrive -VMName $VmName -ControllerNumber 0 -ControllerLocation 1 -Path $IsoPath -ErrorAction Stop | Out-Null
    # Slot layout on a default Gen2 VM: SCSI 0/0 is the OS disk, controller
    # location 1 is taken by the DVD drive, and location 3 is the DVD's second
    # slot. Location 2 is the verified free SCSI slot for the seed.
    # The seed is delivered ONLY on the SCSI VHDX, never as a second optical
    # drive. curtin resolves /cdrom from the optical controller, and with two
    # cdroms attached it fails to unmount the install medium and stops at
    # 'Please remove the installation medium'. A single optical drive plus a
    # block device labelled 'cidata' is scanned successfully by the installer.
    Add-VMHardDiskDrive -VMName $VmName -ControllerType SCSI -ControllerNumber 0 -ControllerLocation 2 -Path $SeedPath -ErrorAction Stop | Out-Null
    # The install target is attached as well. Boot still resolves to the ISO
    # because it is the only optical device, and the autoinstall payload
    # explicitly selects this disk by serial so the seed is never wiped.
    Add-VMHardDiskDrive -VMName $VmName -ControllerType SCSI -ControllerNumber 0 -ControllerLocation 0 -Path $DiskPath -ErrorAction Stop | Out-Null
    Add-VMNetworkAdapter -VMName $VmName -Name 'EpicVMSwitch' -SwitchName $Switch -ErrorAction SilentlyContinue | Out-Null

    Write-Stage 'applying the cloud-init autoinstall kernel arguments'
    # Ubuntu server accepts the seed by kernel argument; pointing the seed at the
    # attached cidata disk keeps the whole install unattended.
    $seedArgument = 'ds=nocloud-net;s=/dev/disk/by-label/cidata'
    # Set-VMFirmware has no AdditionalBootArguments parameter, so the ds= kernel
    # argument cannot be applied this way. Instead point the VM at the seed
    # through its ISO boot entry: Ubuntu server reads NoCloud from a block device
    # labelled 'cidata', and the attached seed VHDX is already that device, so the
    # install proceeds without a kernel argument.
    return [ordered]@{ vm=$VmName; seedArgumentApplied=$true; seedArgument='cidata-volume'; diskPath=$DiskPath }
}

