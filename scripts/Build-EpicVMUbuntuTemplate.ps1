#Requires -RunAsAdministrator
<#
    Builds an immutable EpicVM Ubuntu Server template from a pinned Ubuntu ISO.

    Why Ubuntu rather than the existing Windows flow: a Windows template needs a
    host-side secret that must match a secret baked into the image, and that
    coupling re-breaks on every rebuild, rotation, or restore. Ubuntu guests get a
    per-VM SSH keypair at provision time instead, so there is nothing to drift.

    This builder is intentionally plan-only unless -Execute is supplied, mirroring
    scripts/Build-EpicVMOmarchyTemplate.ps1. It:

      1. verifies the pinned ISO sha256
      2. creates a disposable Gen2 builder VM on a NAT switch with egress
      3. installs Ubuntu unattended via cloud-init NoCloud (autoinstall + a cidata
         seed) - no OOBE, no unattend passes, no sysprep
      4. bakes sshd, the epicvm agent account with NOPASSWD sudo, and base tooling
      5. sanitizes (burn the seed, drop host keys, drop tailscale identity)
      6. exports and publishes an immutable VHDX plus a hash-pinned manifest

    No GPU partition and no Sunshine/streaming: the ubuntu profile is headless and
    SSH-first.
#>
[CmdletBinding()]
param(
    [switch]$Execute,
    [string]$IsoPath = 'E:\EpicVM\install-media\ubuntu-24.04.3-live-server-amd64.iso',
    [string]$ExpectedIsoSha256 = 'c3514bf0056180d09376462a7a1b4f213c1d6e8ea67fae5c25099c6fd3d8274b',
    [string]$TemplateName = 'ubuntu-24.04-lts',
    [string]$TemplateRoot = 'E:\EpicVM\templates',
    [string]$WorkingRoot = 'E:\EpicVM\template-work',
    [string]$BuilderVmName = 'EpicVM-Ubuntu-TemplateBuilder',
    [string]$BuilderSwitch = 'Default Switch',
    [string]$AgentUser = 'epicvm',
    [string]$TimeZone = 'America/New_York',
    [long]$DiskSizeBytes = 12884901888,
    [int]$CpuCount = 4,
    [long]$MemoryBytes = 8589934592,
    [string]$ReportPath
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

function Write-Stage {
    param([string]$Message)
    # Routed to the host stream so stage logging never contaminates a function's
    # return value. A plain Write-Output here would prepend the log lines to the
    # caller's result and break strict-mode property access.
    Write-Host ("[{0}] {1}" -f (Get-Date -Format 'HH:mm:ss'), $Message)
}

function Get-EpicVMUbuntuPlan {
    return [ordered]@{
        templateName = $TemplateName
        isoPath = $IsoPath
        expectedIsoSha256 = $ExpectedIsoSha256
        templateRoot = $TemplateRoot
        workingRoot = $WorkingRoot
        builderVm = $BuilderVmName
        switch = $BuilderSwitch
        agentUser = $AgentUser
        diskSizeBytes = $DiskSizeBytes
        cpuCount = $CpuCount
        memoryBytes = $MemoryBytes
        guestOs = 'Ubuntu Server'
        managementTransport = 'tailscale_ssh'
        consoleBackend = 'none'
        gpu = $false
        bootMode = 'uefi'
        bootPolicy = 'gen2-uefi'
        secureBoot = $false
        vTpm = $false
        fullCopy = $true
        immutable = $true
        noGuestSecrets = $true
        bootstrap = 'per-vm-ssh-keypair'
    }
}

function Test-EpicVMUbuntuPreconditions {
    $plan = Get-EpicVMUbuntuPlan
    $checks = [ordered]@{
        isoPresent = Test-Path -LiteralPath $plan.isoPath -PathType Leaf
        switchPresent = $null -ne (Get-VMSwitch -Name $plan.switch -ErrorAction SilentlyContinue)
        builderVmPresent = $null -ne (Get-VM -Name $plan.builderVm -ErrorAction SilentlyContinue)
        workingRootWritable = $false
        isoHashMatches = $false
    }
    if ($checks.isoPresent) {
        $actual = (Get-FileHash -LiteralPath $plan.isoPath -Algorithm SHA256).Hash.ToLowerInvariant()
        $checks.isoHashMatches = $actual -eq $plan.expectedIsoSha256
        $checks.isoActualSha256 = $actual
    }
    try {
        $parent = Split-Path -Parent $plan.workingRoot
        $probe = Join-Path $parent ('.epicvm-write-probe-' + [guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Path $probe -Force | Out-Null
        Remove-Item $probe -Recurse -Force -ErrorAction SilentlyContinue
        $checks.workingRootWritable = $true
    } catch { $checks.workingRootWritable = $false }
    return $checks
}
function New-EpicVMUbuntuCloudInit {
    <#
        Returns the NoCloud seed files. The autoinstall payload runs on the ISO's
        first boot; the same seed is reused at provision time so a clone is
        reconfigured without a console.
    #>
    param(
        [Parameter(Mandatory)][string]$VmName,
        [Parameter(Mandatory)][string]$AgentUser,
        [Parameter(Mandatory)][string]$PasswordHash,
        [string]$AuthorizedKey = '',
        [string]$TimeZone = 'America/New_York',
        [long]$DiskSizeBytes = 12884901888
    )
    $userData = @'
#cloud-config
# EpicVM unattended Ubuntu install. Generated by Build-EpicVMUbuntuTemplate.ps1.
identity:
  hostname: $VmName
  username: $AgentUser
  password: "$passwordHash"
  # The agent account is locked for interactive console use; the SSH key is the
  # only intended login. PasswordAuthentication is disabled in sshd_config.
  lock_passwd: true
  sudo: ALL=(ALL) NOPASSWD:ALL
  ssh_authorized_keys:
    - $AuthorizedKey
storage:
  layout:
    name: direct
  overwrite: true
  config:
    # The seed is a 64MB cidata VHDX and must never be wiped. Matching
    # the largest disk is the reliable selector on this host because
    # Hyper-V does not expose a stable serial here (Get-VHD .DiskId is
    # empty), so a serial match is not available.
    - type: disk
      ptable: gpt
      match:
        size: largest
      wipe: install
updates: security
timezone: $TimeZone
keyboard:
  layout: us
packages:
  - ca-certificates
  - curl
  - git
  - jq
  - openssh-server
  - python3
  - python3-pip
  - python3-venv
  - build-essential
  - htop
  - unzip
late-commands:
  # NOPASSWD sudo is written explicitly so it survives any image default, and
  # sudo is verified before the install is allowed to report success.
  - curtin in-target -- mkdir -p /etc/sudoers.d
  - curtin in-target -- printf 'epicvm ALL=(ALL) NOPASSWD:ALL\\n' > /etc/sudoers.d/90-epicvm
  - curtin in-target -- chmod 0440 /etc/sudoers.d/90-epicvm
  - curtin in-target -- visudo -c -f /etc/sudoers.d/90-epicvm
  - curtin in-target -- systemctl enable --now ssh
  - curtin in-target -- install -d -m 755 /etc/ssh/sshd_config.d
  - curtin in-target -- printf 'PubkeyAuthentication yes\\nPasswordAuthentication no\\nPermitEmptyPasswords no\\nPermitRootLogin no\\n' > /etc/ssh/sshd_config.d/60-epicvm.conf
  - curtin in-target -- sshd -t
  - curtin in-target -- curl -fsSL https://pk.tailscale.com/stable/ubuntu/noble.gpg | tee /usr/share/keyrings/tailscale-archive-keyring.gpg > /dev/null
  - curtin in-target -- printf 'deb [signed-by=/usr/share/keyrings/tailscale-archive-keyring.gpg] https://pk.tailscale.com/stable/ubuntu noble\\n' > /etc/apt/sources.list.d/tailscale.list
  - curtin in-target -- apt-get update
  - curtin in-target -- apt-get install -y tailscale
  - curtin in-target -- curl -fsSL https://deb.nodesource.com/setup_22.x -o /tmp/nodesource.sh
  - curtin in-target -- bash /tmp/nodesource.sh
  - curtin in-target -- apt-get install -y nodejs
  - curtin in-target -- rm -f /tmp/nodesource.sh
  - curtin in-target -- apt-get clean
shutdown: reboot
